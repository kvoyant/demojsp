-- 1. 은행/금융기관 표준 코드 테이블
CREATE TABLE IF NOT EXISTS TB_BANK_CODE (
    BANK_CD VARCHAR(3) PRIMARY KEY COMMENT '은행코드(금융결제원 3자리 표준코드)',
    BANK_NM VARCHAR(50) NOT NULL COMMENT '은행명',
    BANK_TYPE VARCHAR(20) DEFAULT 'BANK' COMMENT '기관구분 (BANK: 은행, SEC: 증권사)',
    SORT_ORDER INT DEFAULT 0 COMMENT '정렬순서',
    USE_YN CHAR(1) DEFAULT 'Y' COMMENT '사용여부 (Y/N)'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='금융기관 표준 코드 마스터';

-- 2. 대출 신청 대출금 입금/출금 계좌 테이블 (대출 프로세스 연계 자동완성용)
CREATE TABLE IF NOT EXISTS TB_LOAN_ACCOUNT (
    LOAN_NO VARCHAR(50) PRIMARY KEY COMMENT '대출신청번호',
    MEMBER_ID VARCHAR(50) COMMENT '고객ID',
    CUST_NM VARCHAR(50) NOT NULL COMMENT '고객명',
    PRODUCT_NM VARCHAR(100) DEFAULT '햇살론 / 중금리 신용대출' COMMENT '대출상품명',
    BANK_CD VARCHAR(3) NOT NULL COMMENT '등록 은행코드',
    BANK_NM VARCHAR(50) NOT NULL COMMENT '등록 은행명',
    ACCOUNT_NO VARCHAR(50) NOT NULL COMMENT '대출금 입금/출금 계좌번호',
    ACCOUNT_HOLDER_NM VARCHAR(50) NOT NULL COMMENT '예금주명',
    ACCOUNT_TYPE VARCHAR(30) DEFAULT 'DISBURSEMENT_REPAYMENT' COMMENT '계좌용도(대출금입금/원리금출금)',
    REG_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    INDEX IDX_LOAN_MEMBER (MEMBER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='대출신청 대출금 입금/출금 계좌 마스터';

-- 3. 1원 계좌인증 감사 및 이력 관리 테이블
CREATE TABLE IF NOT EXISTS TB_ACCOUNT_CERT_HIST (
    REQ_TX_SEQ VARCHAR(50) PRIMARY KEY COMMENT '인증 트랜잭션 번호',
    MEMBER_ID VARCHAR(50) COMMENT '고객ID',
    CUST_NM VARCHAR(50) NOT NULL COMMENT '신청 고객명',
    BANK_CD VARCHAR(3) NOT NULL COMMENT '은행코드',
    BANK_NM VARCHAR(50) NOT NULL COMMENT '은행명',
    ACCOUNT_NO VARCHAR(50) NOT NULL COMMENT '계좌번호',
    ACCOUNT_HOLDER_NM VARCHAR(50) NOT NULL COMMENT '계좌 예금주명',
    AUTH_CODE VARCHAR(10) NOT NULL COMMENT '적요 인증코드 4자리 (예: 7294)',
    PRINT_TEXT VARCHAR(50) NOT NULL COMMENT '통장 인자문구 (예: 저축7294)',
    STATUS VARCHAR(20) NOT NULL COMMENT '인증상태 (REQUESTED: 1원송금/대기, VERIFIED: 인증성공, FAILED: 5회오류잠금, EXPIRED: 시간만료)',
    PURPOSE VARCHAR(30) NOT NULL COMMENT '업무목적 (LOAN_APPLY: 대출신청연계, COMMON: 타업무공통)',
    LOAN_NO VARCHAR(50) COMMENT '대출신청번호 (대출연계 시)',
    IS_MODIFIED CHAR(1) DEFAULT 'N' COMMENT '자동완성 후 수정여부 (Y/N)',
    FAIL_CNT INT DEFAULT 0 COMMENT '오류 입력횟수 (5회 초과 시 잠금)',
    EXPIRE_DT DATETIME NOT NULL COMMENT '인증 유효만료일시 (10분)',
    VERIFY_DT DATETIME COMMENT '인증 완료일시',
    CLIENT_IP VARCHAR(50) COMMENT '요청 IP',
    USER_AGENT VARCHAR(300) COMMENT '클라이언트 브라우저/디바이스 정보',
    REG_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '최초 요청일시',
    INDEX IDX_ACCT_CERT_LOAN (LOAN_NO),
    INDEX IDX_ACCT_CERT_MEMBER (MEMBER_ID),
    INDEX IDX_ACCT_CERT_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='1원 계좌인증 거래 및 감사 이력 테이블';
