-- 1. 고객 CI 마스터 테이블
CREATE TABLE IF NOT EXISTS TB_CUST_CI (
    CI_VAL VARCHAR(88) PRIMARY KEY COMMENT 'NICE 연계정보(CI 88byte Base64)',
    DI_VAL VARCHAR(64) COMMENT '중복가입확인정보(DI)',
    CUST_ID VARCHAR(50) COMMENT '내부 고객식별번호',
    CUST_NM VARCHAR(50) NOT NULL COMMENT '고객명',
    BIRTH_DATE CHAR(8) NOT NULL COMMENT '생년월일(YYYYMMDD)',
    GENDER CHAR(1) NOT NULL COMMENT '성별 (1:남, 2:여)',
    NATIONAL_INFO CHAR(1) NOT NULL DEFAULT '1' COMMENT '내외국인 (0/1:내국인, 2:외국인)',
    CELL_NO VARCHAR(20) NOT NULL COMMENT '휴대폰번호',
    REG_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '최초인증일시',
    MOD_DT DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    INDEX IDX_CUST_CI_CELL (CELL_NO),
    INDEX IDX_CUST_CI_CUST_ID (CUST_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='고객 CI 마스터';

-- 2. 유의고객(Watchlist / FDS / 사고유의) 관리 테이블 (CI 기반)
CREATE TABLE IF NOT EXISTS TB_WATCHLIST (
    WATCH_SEQ BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '일련번호',
    CI_VAL VARCHAR(88) NOT NULL COMMENT '연계정보(CI)',
    CUST_NM VARCHAR(50) NOT NULL COMMENT '고객명',
    RISK_GRADE VARCHAR(20) NOT NULL DEFAULT 'HIGH' COMMENT '위험등급 (CRITICAL, HIGH, CAUTION)',
    RISK_TYPE VARCHAR(30) NOT NULL COMMENT '유의유형 (FDS_FRAUD: 금융사고, LOAN_DELINQUENT: 연체자, IDENTITY_THEFT: 명의도용, VOICE_PHISHING: 보이스피싱)',
    RISK_REASON VARCHAR(200) NOT NULL COMMENT '유의사유 상세',
    BLOCK_YN CHAR(1) DEFAULT 'Y' COMMENT '거래차단여부(Y/N)',
    REG_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    REG_USER_ID VARCHAR(50) DEFAULT 'SYSTEM' COMMENT '등록자ID',
    UNIQUE KEY UK_WATCHLIST_CI (CI_VAL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='유의고객 관리(CI기반)';

-- 3. 본인인증 이력 및 감사 로그 테이블
CREATE TABLE IF NOT EXISTS TB_CERT_LOG (
    CERT_SEQ BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '인증일련번호',
    REQ_TX_SEQ VARCHAR(64) NOT NULL COMMENT '인증 요청 트랜잭션 번호',
    CHANNEL_TYPE VARCHAR(20) NOT NULL DEFAULT 'PC_WEB' COMMENT '채널구분 (APP, PC_WEB, MO_WEB)',
    AUTH_METHOD VARCHAR(30) NOT NULL COMMENT '인증방식 (SMS_NO_CARRIER: 통신사미지정SMS, MO_DEVICE_AUTH: 기기점유MO인증)',
    CUST_NM VARCHAR(50) NOT NULL COMMENT '입력 고객명',
    BIRTH_DATE CHAR(8) NOT NULL COMMENT '입력 생년월일(YYYYMMDD)',
    CELL_NO VARCHAR(20) COMMENT '휴대폰번호',
    CI_VAL VARCHAR(88) COMMENT '획득된 CI',
    AUTH_TOKEN VARCHAR(100) COMMENT '인증 임시 토큰',
    AUTH_STATUS VARCHAR(20) NOT NULL COMMENT '인증상태 (REQUESTED, VERIFIED, RISK_BLOCKED, EXPIRED, FAILED)',
    ERR_CODE VARCHAR(30) COMMENT '오류코드',
    ERR_MSG VARCHAR(300) COMMENT '오류상세메시지',
    CLIENT_IP VARCHAR(45) COMMENT '요청 IP',
    USER_AGENT VARCHAR(300) COMMENT '접속 User-Agent',
    REQ_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '인증요청일시',
    RES_DT DATETIME COMMENT '인증완료일시',
    INDEX IDX_CERT_TX (REQ_TX_SEQ),
    INDEX IDX_CERT_CI (CI_VAL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='본인인증 감사 이력';

-- 4. 비여신금융거래 약관 테이블
CREATE TABLE IF NOT EXISTS TB_TERMS (
    TERMS_ID VARCHAR(30) PRIMARY KEY COMMENT '약관코드',
    TERMS_TITLE VARCHAR(100) NOT NULL COMMENT '약관명',
    TERMS_VERSION VARCHAR(10) NOT NULL COMMENT '약관버전',
    REQUIRED_YN CHAR(1) DEFAULT 'Y' COMMENT '필수동의여부 (Y/N)',
    CATEGORY VARCHAR(30) NOT NULL COMMENT '약관분류 (NON_CREDIT: 비여신금융, NICE: NICE본인확인, TELCO: 통신사통합)',
    CONTENT MEDIUMTEXT NOT NULL COMMENT '약관전문 내용',
    SORT_ORDER INT DEFAULT 1 COMMENT '정렬순서',
    USE_YN CHAR(1) DEFAULT 'Y' COMMENT '사용여부',
    REG_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='비여신금융거래 본인인증 약관';

-- 5. 약관 동의 이력 테이블
CREATE TABLE IF NOT EXISTS TB_TERMS_AGREE_LOG (
    AGREE_SEQ BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '동의일련번호',
    REQ_TX_SEQ VARCHAR(64) NOT NULL COMMENT '인증 요청 트랜잭션 번호',
    TERMS_ID VARCHAR(30) NOT NULL COMMENT '약관코드',
    AGREE_YN CHAR(1) NOT NULL COMMENT '동의여부(Y/N)',
    AGREE_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '동의일시',
    INDEX IDX_AGREE_TX (REQ_TX_SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='약관 동의 이력';

-- 6. 9/30 이기종 CI 데이터 이관 임시(스테이징) 테이블
CREATE TABLE IF NOT EXISTS TB_CI_MIGRATION_TEMP (
    TEMP_SEQ BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '임시시퀀스',
    LEGACY_SYSTEM_CD VARCHAR(30) NOT NULL COMMENT '이기종 시스템코드 (LEGACY_CORE, CRM_OLD, EXTERNAL_AGENCY)',
    LEGACY_CUST_ID VARCHAR(50) NOT NULL COMMENT '이기종 고객번호',
    CUST_NM VARCHAR(50) NOT NULL COMMENT '고객명',
    CI_VAL VARCHAR(120) NOT NULL COMMENT '이기종 보유 CI (검증전 원본)',
    DI_VAL VARCHAR(100) COMMENT '이기종 보유 DI',
    BIRTH_DATE VARCHAR(20) COMMENT '생년월일',
    GENDER VARCHAR(10) COMMENT '성별 (1:남, 2:여)',
    NATIONAL_INFO VARCHAR(10) DEFAULT '1' COMMENT '내외국인 (1:내국인, 2:외국인)',
    CELL_NO VARCHAR(30) COMMENT '휴대폰번호',
    RRN_HASH VARCHAR(128) COMMENT '주민등록번호 해시값(SHA-256 매핑용)',
    VALID_STATUS VARCHAR(30) DEFAULT 'PENDING' COMMENT '검증상태 (PENDING, VALID, INVALID_LENGTH, INVALID_BASE64, DUPLICATE_CI)',
    MIGRATION_STATUS VARCHAR(20) DEFAULT 'READY' COMMENT '이관상태 (READY, COMPLETED, FAILED)',
    ERROR_MSG VARCHAR(300) COMMENT '오류사유',
    SOURCE_EXTRACT_DT VARCHAR(10) DEFAULT '2026-09-30' COMMENT '추출기준일자(9/30)',
    REG_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '적재일시',
    INDEX IDX_MIG_STATUS (VALID_STATUS, MIGRATION_STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='9/30 이기종 CI 이관 임시 테이블';

-- 7. 이관 실행 이력 및 통계 테이블
CREATE TABLE IF NOT EXISTS TB_CI_MIGRATION_HISTORY (
    HIST_SEQ BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '이관이력 일련번호',
    BATCH_ID VARCHAR(50) NOT NULL COMMENT '배치 실행 ID',
    TOTAL_COUNT INT DEFAULT 0 COMMENT '대상 건수',
    SUCCESS_COUNT INT DEFAULT 0 COMMENT '성공 건수',
    DUPLICATE_COUNT INT DEFAULT 0 COMMENT '중복 건수',
    FAIL_COUNT INT DEFAULT 0 COMMENT '실패 건수',
    START_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '시작일시',
    END_DT DATETIME COMMENT '종료일시',
    STATUS VARCHAR(20) NOT NULL COMMENT '진행상태 (RUNNING, COMPLETED, FAILED)',
    EXEC_BY VARCHAR(50) DEFAULT 'SYSTEM_ADMIN' COMMENT '실행자ID'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='CI 이관 실행 이력';

-- 8. 금융 SMS 발송 큐 테이블 (실제 SMS 모듈 연동용)
CREATE TABLE IF NOT EXISTS TB_SMS_SEND_QUEUE (
    SMS_SEQ BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT 'SMS발송시퀀스',
    DEST_PHONE VARCHAR(20) NOT NULL COMMENT '수신번호',
    SEND_PHONE VARCHAR(20) NOT NULL COMMENT '발신번호(금융사대표번호)',
    MSG_BODY VARCHAR(1000) NOT NULL COMMENT '메시지내용(인증번호)',
    MSG_TYPE VARCHAR(10) DEFAULT 'SMS' COMMENT '메시지타입 (SMS, LMS, MMS)',
    REQ_TX_SEQ VARCHAR(64) COMMENT '본인인증 트랜잭션번호',
    SEND_STATUS VARCHAR(20) DEFAULT 'PENDING' COMMENT '발송상태 (PENDING:대기, SENT:성공, FAILED:실패)',
    EXT_RESULT_CODE VARCHAR(50) COMMENT 'SMS중계사 결과코드',
    REG_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '발송요청일시',
    SENT_DT DATETIME COMMENT '실제발송완료일시',
    INDEX IDX_SMS_TX (REQ_TX_SEQ),
    INDEX IDX_SMS_STATUS (SEND_STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='금융 SMS 발송 큐';
