-- 공통업무 : 저축은행 로그인 정책(개인, 상담사, 관리자, 권한) DDL
-- ==============================================================

-- 1. 저축은행 회원/사용자 마스터 테이블
CREATE TABLE IF NOT EXISTS TB_MEMBER (
    MEMBER_ID VARCHAR(50) PRIMARY KEY COMMENT '회원/사용자ID (사번 또는 고객ID)',
    MEMBER_TYPE VARCHAR(20) NOT NULL COMMENT '회원유형 (INDIVIDUAL: 개인, COUNSELOR: 상담사/모집인, ADMIN: 관리자/심사역)',
    ROLE_CD VARCHAR(30) NOT NULL COMMENT '권한코드 (ROLE_CUSTOMER, ROLE_COUNSELOR, ROLE_ADMIN)',
    PASSWORD VARCHAR(200) NOT NULL COMMENT '비밀번호 해시 (SHA-256)',
    MEMBER_NM VARCHAR(50) NOT NULL COMMENT '사용자명',
    CELL_NO VARCHAR(20) NOT NULL COMMENT '휴대폰번호',
    EMAIL VARCHAR(100) COMMENT '이메일주소',
    CI_VAL VARCHAR(88) COMMENT 'NICE 본인인증 연계정보 (개인고객 본인인증 로그인용)',
    LOGIN_FAIL_CNT INT DEFAULT 0 COMMENT '비밀번호 연속 실패 횟수 (5회 도달 시 잠금)',
    LOCK_YN CHAR(1) DEFAULT 'N' COMMENT '계정 잠금 여부 (Y/N)',
    LAST_LOGIN_DT DATETIME COMMENT '최종 로그인 일시',
    LAST_PW_MOD_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '최종 비밀번호 변경일시 (90일 만료 체크용)',
    USE_YN CHAR(1) DEFAULT 'Y' COMMENT '계정 활성 여부 (Y/N)',
    REG_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '가입/등록 일시',
    INDEX IDX_MEMBER_CI (CI_VAL),
    INDEX IDX_MEMBER_TYPE (MEMBER_TYPE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='저축은행 사용자 및 로그인 계정';

-- 2. 전자금융 로그인 감사 로그 테이블
CREATE TABLE IF NOT EXISTS TB_LOGIN_LOG (
    LOG_SEQ BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '로그일련번호',
    MEMBER_ID VARCHAR(50) NOT NULL COMMENT '시도 계정 ID',
    MEMBER_TYPE VARCHAR(20) COMMENT '회원유형',
    LOGIN_METHOD VARCHAR(30) NOT NULL COMMENT '로그인수단 (PASSWORD, NICE_CI_AUTH, TWO_FACTOR_OTP)',
    LOGIN_SUCCESS_YN CHAR(1) NOT NULL COMMENT '로그인 성공 여부 (Y/N)',
    FAIL_REASON VARCHAR(200) COMMENT '실패 사유 (PW_MISMATCH, LOCKED, 2FA_MISMATCH 등)',
    CLIENT_IP VARCHAR(45) COMMENT '접속 IP 주소',
    USER_AGENT VARCHAR(300) COMMENT '브라우저 정보',
    LOGIN_DT DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '로그인 시도 일시',
    INDEX IDX_LOGIN_MEMBER (MEMBER_ID),
    INDEX IDX_LOGIN_DT (LOGIN_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='전자금융 로그인 감사 로그';
